package io.qiao.quote;

/**
 * 某檔股票目前的行情狀態（清單上收盤價那一格要顯示什麼）。
 */
public enum QuoteStatus {

	/** 這次啟動後還沒查過（排程還沒輪到）→「更新中…（上次收盤價 X）」 */
	UPDATING,

	/** 最近一次查詢成功 → 顯示收盤價 */
	OK,

	/** 最近一次查詢失敗（連不上、被擋）→「未取得（上次收盤價 X）」 */
	UNAVAILABLE,

	/**
	 * 上市、上櫃近期（本月與上月）都沒有成交資料 →「近期無成交資料（可能停止交易或已下市）」。
	 * 不說「查無此代號」：已存在的持股查不到，通常是長期停止交易或下市，不是代號錯誤。
	 * 往前多查幾個月找得到最後成交時，資料庫的上次收盤價會更新成那一天，一併顯示。
	 */
	NO_RECENT_TRADE
}
